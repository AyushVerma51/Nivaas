/** Return a stable, keyless image URL for a city or visual category. */
export function getImageFallback(query: string, _width = 1200): string {
  const normalize = (value: string) =>
    ` ${value.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, " ").trim()} `;
  const text = normalize(query);
  const placePhoto = Object.entries(PLACE_IMAGES)
    .sort(([a], [b]) => b.length - a.length)
    .find(([name]) => text.startsWith(normalize(name)));
  if (placePhoto) return placePhoto[1];

  const photos = Object.entries(PHOTOS).sort(([a], [b]) => b.length - a.length);
  const match =
    photos.find(([key]) => text.startsWith(normalize(key))) ??
    photos.find(([key]) => text.includes(normalize(key)));
  const id = match?.[1] ?? "photo-1524492412937-b28074a5d7da";
  return `/images/places/${id}.jpg`;
}
